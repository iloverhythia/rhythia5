export const uiColorRow = (label: string, key: UIColorKey): SettingsRow => ({
  kind: "color",
  label,
  get: () => uiColor(key),
  set: (color) => ConfigManager.setExtra(`ui.${key}`, toHexColor({ a: uiColor(key).a, ...color })),
  defaultValue: parseHexColor(UI_COLOR_DEFAULTS[key]),
  opacity: {
    get: () => uiColor(key).a / 255,
    set: (value) => ConfigManager.setExtra(`ui.${key}`, toHexColor({ ...uiColor(key), a: value * 255 })),
  },
});

const uiSlider = (label: string, key: "pauseUiOpacity" | "gradeSsSaturation" | "gradeSsValue"): SettingsRow => ({
  kind: "slider",
  label,
  min: 0,
  max: 1,
  step: 0.001,
  defaultValue: UI_COLOR_DEFAULTS[key],
  get: () => uiSetting(key),
  set: (value) => ConfigManager.setExtra(`ui.${key}`, value),
});

